  <p>Coming down the northern face of Hải Vân Pass, the road drops to Lăng Cô Bay — a long crescent of white sand backed by mountains on three sides, recognised in 2009 as one of the world's 30 most beautiful bays. The village of Lăng Cô is a small fishing community strung along the beach road, with a line of seafood restaurants serving the morning's catch. This is the lunch stop, and the lunch is the point: Lăng Cô is famous throughout central Vietnam for its fresh seafood, and particularly for <strong>BBQ oysters and clams</strong> cooked directly on charcoal at the tables outside. Order the oysters with spring onion and peanut oil, the clams with lemongrass and chilli, and whatever whole fish looks best. Everything will be fresh, everything will be cheap, and after the Hải Vân Pass it will taste extraordinary.</p>
